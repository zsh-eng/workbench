import { chromium, type FullConfig } from "@playwright/test";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { mockApi } from "./mock-api";

export const SAMPLE_EPUB_PATH = fileURLToPath(
  new URL("../../fixtures/sample.epub", import.meta.url),
);
export const DATABASE_MODULE = "/src/lib/sync-v2/db.ts";

/** The rows that the real importer writes for the sample book. */
export type PreparedLibrary = Record<string, Record<string, unknown>[]>;

/** Where this run's prepared library is written, one file per port. */
export function preparedLibraryPath(baseURL: string): string {
  const port = new URL(baseURL).port;
  return fileURLToPath(
    new URL(
      `../../../node_modules/.cache/reader-e2e/library-${port}.json`,
      import.meta.url,
    ),
  );
}

/**
 * Runs once before the suite. It loads the app, so the first test of each
 * worker meets a warm Vite module graph instead of a cold one, and imports
 * the sample book once through the real importer. Tests restore these rows
 * (the `localBook` fixture) instead of importing the book again.
 */
export default async function globalSetup(config: FullConfig) {
  const baseURL = config.projects[0]!.use.baseURL!;
  const browser = await chromium.launch();
  try {
    const context = await browser.newContext({ serviceWorkers: "block" });
    const remote = await mockApi(context);
    const page = await context.newPage();
    await page.goto(baseURL);
    const importButton = page.getByRole("button", {
      name: "Choose EPUB files",
      exact: true,
    });
    // A cold dev server compiles the whole application graph here.
    await importButton.waitFor({ timeout: 120_000 });
    const [fileChooser] = await Promise.all([
      page.waitForEvent("filechooser"),
      importButton.click(),
    ]);
    await fileChooser.setFiles(SAMPLE_EPUB_PATH);
    await page
      .getByRole("heading", { name: /Alice.*Adventures.*Wonderland/i })
      .waitFor({ timeout: 30_000 });
    // Blobs need an explicit encoding when crossing the Playwright boundary.
    // Keep the stored rows, including their schema, generated by the real importer.
    const snapshot: PreparedLibrary = await page.evaluate(
      async (modulePath) => {
        const { syncV2Db: db } = await import(modulePath);
        const tables = ["books", "files", "bookFiles", "bookMaterializations"];
        return Object.fromEntries(
          await Promise.all(
            tables.map(async (table) => {
              const rows = await db.table(table).toArray();
              for (const row of rows) {
                for (const [key, value] of Object.entries(row)) {
                  if (!(value instanceof Blob)) continue;
                  const dataUrl = await new Promise<string>(
                    (resolve, reject) => {
                      const reader = new FileReader();
                      reader.onload = () => resolve(reader.result as string);
                      reader.onerror = () => reject(reader.error);
                      reader.readAsDataURL(value);
                    },
                  );
                  row[key] = { blobDataUrl: dataUrl };
                }
              }
              return [table, rows];
            }),
          ),
        );
      },
      DATABASE_MODULE,
    );
    if (remote.unexpected.length)
      throw new Error(`Unexpected API requests: ${remote.unexpected}`);
    const path = preparedLibraryPath(baseURL);
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, JSON.stringify(snapshot));
  } finally {
    await browser.close();
  }
}
