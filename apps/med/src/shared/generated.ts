import { z } from "zod";

// Files that a tool writes: lockfiles, build output, snapshots, and files
// whose header or Git attributes say so (docs/GENERATED.md). The host marks
// each file of a review; this module holds the rules that need no I/O.

export const generatedKinds = [
  "lockfile",
  "output",
  "snapshot",
  "minified",
  "named",
  "header",
  "attributes",
] as const;
export type GeneratedKind = (typeof generatedKinds)[number];
export const generatedMarkSchema = z.object({
  kind: z.enum(generatedKinds),
  /** The file that the header names as its generator, relative to the checkout. */
  source: z.string().max(4096).optional(),
});
export type GeneratedMark = z.infer<typeof generatedMarkSchema>;

/** What the reader sees for each kind. */
export const GENERATED_LABELS: Record<GeneratedKind, string> = {
  lockfile: "Lockfile",
  output: "Build output",
  snapshot: "Snapshot",
  minified: "Minified",
  named: "Generated",
  header: "Generated",
  attributes: "Marked generated",
};

const nameOf = (path: string) => path.slice(path.lastIndexOf("/") + 1);

// Package manager lockfiles have no shared format, so they are known by name:
// the common ones, plus the `*.lock` and `*-lock.json|yaml` conventions.
const lockfiles = new Set([
  "package-lock.json",
  "npm-shrinkwrap.json",
  "go.sum",
  "Package.resolved",
  "gradle.lockfile",
  "packages.lock.json",
  ".terraform.lock.hcl",
  "conda-lock.yml",
]);
export function isLockfile(path: string): boolean {
  const name = nameOf(path);
  return lockfiles.has(name) || /\.lockb?$|-lock\.(?:json|ya?ml)$/i.test(name);
}

/** Folders that only tools write. `build/` and `out/` are left out: they
 * often hold hand-written scripts. */
const OUTPUT =
  /(?:^|\/)(?:dist|\.vite|\.next|\.nuxt|\.svelte-kit|\.turbo|coverage|__generated__|node_modules)\//;
const SNAPSHOT = /(?:^|\/)(?:__snapshots__|__Snapshots__)\/|\.snap$|-snapshots\//;
const MINIFIED = /\.min\.(?:js|mjs|css)$|\.(?:js|mjs|cjs|css)\.map$/;
const NAMED =
  /\.(?:generated|gen)\.[^/.]+$|\.g\.dart$|\.pb\.go$|_pb2(?:_grpc)?\.pyi?$|\.designer\.cs$/;

/** The mark that a path alone gives, or null. */
export function generatedByPath(path: string): GeneratedMark | null {
  if (isLockfile(path)) return { kind: "lockfile" };
  if (SNAPSHOT.test(path)) return { kind: "snapshot" };
  if (OUTPUT.test(path)) return { kind: "output" };
  if (MINIFIED.test(path)) return { kind: "minified" };
  if (NAMED.test(nameOf(path))) return { kind: "named" };
  return null;
}

/** Lines of a file's start that a header may be in. */
export const HEADER_LINES = 5;
const HEADER =
  /@generated\b|\bdo not (?:edit|modify)\b|\bauto-?generated\b|\bautomatically generated\b|^\W*code generated\b/i;
const GENERATOR = /\bgenerated (?:by|from|with) `?([\w./-]+\/[\w.-]+\.\w+)`?/i;

/** The mark that a file's first lines give, or null. A header that names a
 * generator by path, such as "Generated by scripts/x.ts", gives it as source. */
export function generatedByHeader(lines: readonly string[]): GeneratedMark | null {
  const head = lines.slice(0, HEADER_LINES);
  if (!head.some((line) => HEADER.test(line))) return null;
  for (const line of head) {
    const source = GENERATOR.exec(line)?.[1];
    if (source && !source.startsWith("/") && !source.split("/").includes(".."))
      return { kind: "header", source: source.replace(/^\.\//, "") };
  }
  return { kind: "header" };
}

/** Package ecosystems, for a lockfile's manifests and the commands that write it. */
export type Ecosystem = "npm" | "cargo" | "go" | "ruby" | "python" | "swift" | "other";
const LOCK_ECOSYSTEMS: [RegExp, Ecosystem][] = [
  [/^(?:bun\.lockb?|package-lock\.json|npm-shrinkwrap\.json|yarn\.lock|pnpm-lock\.ya?ml)$/, "npm"],
  [/^Cargo\.lock$/, "cargo"],
  [/^go\.sum$/, "go"],
  [/^Gemfile\.lock$/, "ruby"],
  [/^(?:poetry|uv|pdm|Pipfile)\.lock$/, "python"],
  [/^Package\.resolved$/, "swift"],
];
const MANIFESTS: [RegExp, Ecosystem][] = [
  [/^package\.json$/, "npm"],
  [/^Cargo\.toml$/, "cargo"],
  [/^go\.mod$/, "go"],
  [/^(?:Gemfile|.+\.gemspec)$/, "ruby"],
  [/^(?:pyproject\.toml|Pipfile|requirements.*\.txt)$/, "python"],
  [/^Package\.swift$/, "swift"],
];
export function lockfileEcosystem(path: string): Ecosystem {
  const name = nameOf(path);
  return LOCK_ECOSYSTEMS.find(([rule]) => rule.test(name))?.[1] ?? "other";
}
export function manifestEcosystem(path: string): Ecosystem | null {
  const name = nameOf(path);
  return MANIFESTS.find(([rule]) => rule.test(name))?.[1] ?? null;
}

/**
 * The file in `paths` whose change made a generated file, if one is there:
 * a lockfile's manifests (the nearest one of its ecosystem at or below its
 * folder), a snapshot's test, a minified or map file's source, and the
 * generator that a header names.
 */
export function generatedSource(
  path: string,
  mark: GeneratedMark,
  paths: ReadonlySet<string>,
): string | null {
  if (mark.source) return paths.has(mark.source) ? mark.source : null;
  const folder = path.slice(0, path.lastIndexOf("/") + 1);
  if (mark.kind === "lockfile") {
    const ecosystem = lockfileEcosystem(path);
    let best: string | null = null;
    for (const candidate of paths) {
      if (!candidate.startsWith(folder) || manifestEcosystem(candidate) !== ecosystem) continue;
      // The manifest beside the lockfile first, then the shallowest one.
      if (!best || candidate.split("/").length < best.split("/").length) best = candidate;
    }
    return best;
  }
  if (mark.kind === "snapshot") {
    // __snapshots__/name.test.ts.snap → name.test.ts; name.spec.ts-snapshots/x.png → name.spec.ts.
    const snap = /^(.*\/)?__snapshots__\/(.+)\.snap$/i.exec(path);
    const shots = /^(.*?)-snapshots\//.exec(path);
    const test = snap ? `${snap[1] ?? ""}${snap[2]}` : shots ? shots[1]! : null;
    return test && paths.has(test) ? test : null;
  }
  if (mark.kind === "minified") {
    const plain = path.replace(/\.map$/, "").replace(/\.min(\.(?:js|mjs|css))$/, "$1");
    return plain !== path && paths.has(plain) ? plain : null;
  }
  return null;
}
