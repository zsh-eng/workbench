import { z } from "zod";
import { editSessionSchema } from "./protocol";
import type { RouteContract } from "./routes";

// Files that a tool writes: lockfiles, build output, snapshots, and files
// whose header or Git attributes say so (docs/GENERATED.md). The host marks
// each file of a review; this module holds the rules that need no I/O.

export const generatedKinds = [
  "lockfile",
  "output",
  "snapshot",
  "minified",
  "named",
  "header",
  "attributes",
  "declared",
] as const;
export type GeneratedKind = (typeof generatedKinds)[number];
export const generatedMarkSchema = z.object({
  kind: z.enum(generatedKinds),
  /** The file that the header names as its generator, relative to the checkout. */
  source: z.string().max(4096).optional(),
});
export type GeneratedMark = z.infer<typeof generatedMarkSchema>;

/** What the reader sees for each kind. */
export const GENERATED_LABELS: Record<GeneratedKind, string> = {
  lockfile: "Lockfile",
  output: "Build output",
  snapshot: "Snapshot",
  minified: "Minified",
  named: "Generated",
  header: "Generated",
  attributes: "Marked generated",
  declared: "Marked generated",
};

const nameOf = (path: string) => path.slice(path.lastIndexOf("/") + 1);

// Package manager lockfiles have no shared format, so they are known by name:
// the common ones, plus the `*.lock` and `*-lock.json|yaml` conventions.
const lockfiles = new Set([
  "package-lock.json",
  "npm-shrinkwrap.json",
  "go.sum",
  "Package.resolved",
  "gradle.lockfile",
  "packages.lock.json",
  ".terraform.lock.hcl",
  "conda-lock.yml",
]);
export function isLockfile(path: string): boolean {
  const name = nameOf(path);
  return lockfiles.has(name) || /\.lockb?$|-lock\.(?:json|ya?ml)$/i.test(name);
}

/** Folders that only tools write. `build/` and `out/` are left out: they
 * often hold hand-written scripts. */
const OUTPUT =
  /(?:^|\/)(?:dist|\.vite|\.next|\.nuxt|\.svelte-kit|\.turbo|coverage|__generated__|node_modules)\//;
const SNAPSHOT = /(?:^|\/)(?:__snapshots__|__Snapshots__)\/|\.snap$|-snapshots\//;
const MINIFIED = /\.min\.(?:js|mjs|css)$|\.(?:js|mjs|cjs|css)\.map$/;
const NAMED =
  /\.(?:generated|gen)\.[^/.]+$|\.g\.dart$|\.pb\.go$|_pb2(?:_grpc)?\.pyi?$|\.designer\.cs$/;

/** The mark that a path alone gives, or null. */
export function generatedByPath(path: string): GeneratedMark | null {
  if (isLockfile(path)) return { kind: "lockfile" };
  if (SNAPSHOT.test(path)) return { kind: "snapshot" };
  if (OUTPUT.test(path)) return { kind: "output" };
  if (MINIFIED.test(path)) return { kind: "minified" };
  if (NAMED.test(nameOf(path))) return { kind: "named" };
  return null;
}

/** Lines of a file's start that a header may be in. */
export const HEADER_LINES = 5;
const HEADER =
  /@generated\b|\bdo not (?:edit|modify)\b|\bauto-?generated\b|\bautomatically generated\b|^\W*code generated\b/i;
const GENERATOR = /\bgenerated (?:by|from|with) `?([\w./-]+\/[\w.-]+\.\w+)`?/i;

/** The mark that a file's first lines give, or null. A header that names a
 * generator by path, such as "Generated by scripts/x.ts", gives it as source. */
export function generatedByHeader(lines: readonly string[]): GeneratedMark | null {
  const head = lines.slice(0, HEADER_LINES);
  if (!head.some((line) => HEADER.test(line))) return null;
  for (const line of head) {
    const source = GENERATOR.exec(line)?.[1];
    if (source && !source.startsWith("/") && !source.split("/").includes(".."))
      return { kind: "header", source: source.replace(/^\.\//, "") };
  }
  return { kind: "header" };
}

/** Package ecosystems, for a lockfile's manifests and the commands that write it. */
export type Ecosystem = "npm" | "cargo" | "go" | "ruby" | "python" | "swift" | "other";
const LOCK_ECOSYSTEMS: [RegExp, Ecosystem][] = [
  [/^(?:bun\.lockb?|package-lock\.json|npm-shrinkwrap\.json|yarn\.lock|pnpm-lock\.ya?ml)$/, "npm"],
  [/^Cargo\.lock$/, "cargo"],
  [/^go\.sum$/, "go"],
  [/^Gemfile\.lock$/, "ruby"],
  [/^(?:poetry|uv|pdm|Pipfile)\.lock$/, "python"],
  [/^Package\.resolved$/, "swift"],
];
const MANIFESTS: [RegExp, Ecosystem][] = [
  [/^package\.json$/, "npm"],
  [/^Cargo\.toml$/, "cargo"],
  [/^go\.mod$/, "go"],
  [/^(?:Gemfile|.+\.gemspec)$/, "ruby"],
  [/^(?:pyproject\.toml|Pipfile|requirements.*\.txt)$/, "python"],
  [/^Package\.swift$/, "swift"],
];
export function lockfileEcosystem(path: string): Ecosystem {
  const name = nameOf(path);
  return LOCK_ECOSYSTEMS.find(([rule]) => rule.test(name))?.[1] ?? "other";
}
export function manifestEcosystem(path: string): Ecosystem | null {
  const name = nameOf(path);
  return MANIFESTS.find(([rule]) => rule.test(name))?.[1] ?? null;
}

/**
 * The file in `paths` whose change made a generated file, if one is there:
 * a lockfile's manifests (the nearest one of its ecosystem at or below its
 * folder), a snapshot's test, a minified or map file's source, and the
 * generator that a header names.
 */
export function generatedSource(
  path: string,
  mark: GeneratedMark,
  paths: ReadonlySet<string>,
): string | null {
  if (mark.source) return paths.has(mark.source) ? mark.source : null;
  const folder = path.slice(0, path.lastIndexOf("/") + 1);
  if (mark.kind === "lockfile") {
    const ecosystem = lockfileEcosystem(path);
    let best: string | null = null;
    for (const candidate of paths) {
      if (!candidate.startsWith(folder) || manifestEcosystem(candidate) !== ecosystem) continue;
      // The manifest beside the lockfile first, then the shallowest one.
      if (!best || candidate.split("/").length < best.split("/").length) best = candidate;
    }
    return best;
  }
  if (mark.kind === "snapshot") {
    // __snapshots__/name.test.ts.snap → name.test.ts; name.spec.ts-snapshots/x.png → name.spec.ts.
    const snap = /^(.*\/)?__snapshots__\/(.+)\.snap$/i.exec(path);
    const shots = /^(.*?)-snapshots\//.exec(path);
    const test = snap ? `${snap[1] ?? ""}${snap[2]}` : shots ? shots[1]! : null;
    return test && paths.has(test) ? test : null;
  }
  if (mark.kind === "minified") {
    const plain = path.replace(/\.map$/, "").replace(/\.min(\.(?:js|mjs|css))$/, "$1");
    return plain !== path && paths.has(plain) ? plain : null;
  }
  return null;
}

/** What deps.dev says of one package version (docs/GENERATED.md). */
export const dependencyInfoSchema = z.object({
  name: z.string(),
  version: z.string(),
  licence: z.string().optional(),
  /** When the registry published the version, in Unix milliseconds. */
  publishedAt: z.number().optional(),
  /** Security advisories that name the version. */
  advisories: z.number().int().nonnegative().optional(),
  deprecated: z.boolean().optional(),
  /** deps.dev does not know the version, as for a private package. */
  unknown: z.boolean().optional(),
  /** The lookup failed this time; nothing is kept. */
  failed: z.boolean().optional(),
});
export type DependencyInfo = z.infer<typeof dependencyInfoSchema>;
const packageName = z
  .string()
  .max(214)
  .regex(/^(?:@[a-z0-9][\w.~-]*\/)?[a-z0-9][\w.~-]*$/i);
const packageVersion = z.string().regex(/^[0-9A-Za-z][\w.+-]{0,63}$/);
export const provenanceSchema = z.object({
  /** An agent edited the file with an edit tool: a hand edit of generated output. */
  edited: z.boolean().optional(),
  /** The last command of the sessions that writes such a file. */
  command: z.string().optional(),
});
export type Provenance = z.infer<typeof provenanceSchema>;

export const generatedRoutes = {
  /** Licences, release dates, and advisories of npm package versions, from
   * deps.dev. The browser asks only after the reader turns lookups on. */
  dependencies: {
    method: "POST",
    path: "/api/dependencies",
    input: z.object({
      packages: z.array(z.object({ name: packageName, version: packageVersion })).max(100),
    }),
    output: z.object({ packages: z.array(dependencyInfoSchema) }),
  },
  /** Which generated files the thread's agent sessions edited by hand, and
   * which command wrote the others. */
  provenance: {
    method: "POST",
    path: "/api/review/provenance",
    input: z.object({
      repo: z.string().min(1).max(4096),
      sessions: z.array(editSessionSchema).max(8),
      files: z
        .array(
          z.object({
            path: z.string().min(1).max(4096),
            kind: z.enum(generatedKinds),
            source: z.string().max(4096).optional(),
          }),
        )
        .max(2000),
    }),
    output: z.object({ files: z.record(z.string(), provenanceSchema) }),
    maxBody: 1024 * 1024,
  },
} satisfies Record<string, RouteContract>;

const PACKAGE_COMMANDS: Record<Ecosystem, RegExp> = {
  npm: /\b(?:bun|npm|pnpm|yarn)\s+(?:install|i|add|remove|rm|uninstall|update|up|upgrade|ci|link)\b|^\s*yarn\s*$/,
  cargo: /\bcargo\s+(?:build|update|add|remove|check|test|run|fetch|generate-lockfile)\b/,
  go: /\bgo\s+(?:mod\s+(?:tidy|download)|get|build|test)\b/,
  ruby: /\bbundle(?:\s+(?:install|update|add|lock))?\s*$|\bbundle\s+(?:install|update|add|lock)\b/,
  python: /\b(?:uv|poetry|pdm|pipenv)\s+(?:lock|add|remove|sync|update|install)\b/,
  swift: /\bswift\s+(?:package\s+(?:resolve|update)|build)\b/,
  other:
    /\b(?:bun|npm|pnpm|yarn|cargo|go|bundle|uv|poetry|pdm|pipenv|swift)\s+(?:install|add|remove|update|lock|sync|mod|get|build)\b/,
};
const TEST_RUNNER = /\b(?:test|vitest|jest|playwright)\b/;
const UPDATE_SNAPSHOTS = /\s(?:-u|--update(?:-snapshots|Snapshot)?)(?=\s|$)/;
const BUILD = /\b(?:build|vite|tsc|webpack|rollup|esbuild|tsup)\b/;
const GENERATE = /\b(?:generat\w*|codegen|protoc)\b/;

/**
 * The part of a shell command that writes a generated file of this kind, or
 * null: a package manager for a lockfile, a test runner that updates
 * snapshots, a build tool for output, or a command that names the header's
 * generator. A command such as `cd app && bun install | tail` gives `bun install`.
 */
export function commandWrites(
  file: { path: string; kind: GeneratedKind; source?: string },
  command: string,
): string | null {
  const generator = file.source ? nameOf(file.source).replace(/\.[^.]+$/, "") : undefined;
  const writes = (part: string) => {
    if (generator) return part.includes(generator);
    switch (file.kind) {
      case "lockfile":
        return PACKAGE_COMMANDS[lockfileEcosystem(file.path)].test(part);
      case "snapshot":
        return TEST_RUNNER.test(part) && UPDATE_SNAPSHOTS.test(part);
      case "output":
      case "minified":
        return BUILD.test(part);
      default:
        return GENERATE.test(part);
    }
  };
  for (const part of command.split(/&&|\|\||[;|\n]/)) {
    // Without its redirections, such as 2>&1.
    const trimmed = part.replace(/\s+(?:\d?>>?|&>)\s*(?:&\d|\S+)/g, "").trim();
    if (trimmed && writes(trimmed))
      return trimmed.length > 80 ? `${trimmed.slice(0, 79)}…` : trimmed;
  }
  return null;
}
