/** An icon's path on Phosphor's 256-unit grid, for a control that draws it
 * itself, such as Copy comments turning into a check. */
export function iconPath(name: Exclude<IconName, DrawnName>) {
  return phosphor[name];
}

/** Every icon name, for the elements page. */
export const iconNames = [...Object.keys(phosphor), ...Object.keys(drawn)] as IconName[];

/** The width of an icon's lines on screen. Phosphor's regular weight draws
 * them 16 units of 256 wide: about 0.9 px at 15 px. A round stroke on the
 * filled shape adds the rest, so a small icon keeps its lines. */
const LINE = 1.1;

export function Icon({
  name,
  size = 16,
  style,
}: {
  name: IconName;
  size?: number;
  style?: CSSProperties;
}) {
  const box = {
    width: size,
    height: size,
    "aria-hidden": true,
    focusable: false,
    style: { flexShrink: 0, ...style },
  } as const;
  if (name in drawn)
    return (
      <svg
        {...box}
        viewBox="0 0 16 16"
        fill="none"
        stroke="currentColor"
        strokeWidth={Math.min(1.5, (LINE * 16) / size)}
        strokeLinecap="round"
        strokeLinejoin="round"
      >
        {drawn[name as DrawnName]}
      </svg>
    );
  return (
    <svg {...box} viewBox="0 0 256 256" fill="currentColor">
      <path
        d={phosphor[name as Exclude<IconName, DrawnName>]}
        stroke="currentColor"
        strokeWidth={Math.max(0, Math.min(8, (LINE * 256) / size - 16))}
        strokeLinejoin="round"
        {...(mirrored.has(name) && { transform: "matrix(-1 0 0 1 256 0)" })}
      />
    </svg>
  );
}
