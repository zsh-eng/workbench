import { expect, test } from "vitest";
import {
  commandWrites,
  generatedByHeader,
  generatedByPath,
  generatedSource,
} from "../../src/shared/generated";
import { parseReviewPatch } from "../../src/shared/review";
import { lockfileChanges, manifestChanges } from "../../src/web/data/dependencies";

// The rules that docs/GENERATED.md names, on small inputs: each lockfile
// format, and the paths, headers, and commands that the integration tests do
// not reach.

const patch = (path: string, lines: string[]) =>
  `diff --git a/${path} b/${path}\nindex 1111111..2222222 100644\n--- a/${path}\n+++ b/${path}\n@@ -1,${lines.filter((line) => !line.startsWith("+")).length} +1,${lines.filter((line) => !line.startsWith("-")).length} @@\n${lines.join("\n")}\n`;
const changes = (path: string, lines: string[]) =>
  lockfileChanges(parseReviewPatch(patch(path, lines))[0]!);

test("each lockfile format names the packages whose versions changed", () => {
  expect(
    changes("bun.lock", [
      '     "packages": {',
      '-    "@types/node": ["@types/node@26.6.1", "", {}, "sha512-a"],',
      '+    "@types/node": ["@types/node@26.6.2", "", {}, "sha512-b"],',
      '+    "zod": ["zod@4.6.5", "", {}, "sha512-c"],',
      '     "react": ["react@19.3.0", "", {}, "sha512-d"],',
    ]),
  ).toEqual({ updated: ["@types/node"], added: ["zod"], removed: [] });
  expect(
    changes("package-lock.json", [
      '     "node_modules/pg": {',
      '-      "version": "8.13.0",',
      '+      "version": "8.16.3",',
      '       "license": "MIT"',
    ]),
  ).toEqual({ updated: ["pg"], added: [], removed: [] });
  expect(
    changes("yarn.lock", [
      " pg@^8.13.0:",
      '-  version "8.13.0"',
      '+  version "8.16.3"',
      ' "@babel/core@npm:^7.0.0":',
      "-  version: 7.25.0",
      "+  version: 7.26.0",
    ]).updated,
  ).toEqual(["@babel/core", "pg"]);
  expect(
    changes("pnpm-lock.yaml", [
      "   pg@8.13.0:",
      "-  pg-pool@3.7.0:",
      "+  pg-pool@3.10.1(pg@8.16.3):",
    ]),
  ).toEqual({ updated: ["pg-pool"], added: [], removed: [] });
});

test("a manifest's sections, ranges, and major bumps", () => {
  const [pg, react] = manifestChanges(
    '{ "dependencies": { "react": "^0.14.0", "pg": "workspace:*" } }',
    '{ "dependencies": { "react": "~0.15.1", "pg": "workspace:^" } }',
  )!;
  // Below 1.0 a minor version breaks; a range of no one version shows as written.
  expect(react).toMatchObject({
    name: "react",
    fromVersion: "0.14.0",
    toVersion: "0.15.1",
    major: true,
  });
  expect(pg).toMatchObject({ name: "pg", from: "workspace:*", to: "workspace:^", major: false });
  expect(pg!.toVersion).toBeUndefined();
  expect(manifestChanges("{", "{}")).toBeNull();
});

test("paths, headers, and sources", () => {
  expect(generatedByPath("apps/med/dist/cli.js")).toEqual({ kind: "output" });
  expect(generatedByPath("apps/reader/.vite/deps/react.js")).toEqual({ kind: "output" });
  // build/ often holds scripts that people write.
  expect(generatedByPath("build/release.sh")).toBeNull();
  expect(generatedByPath("src/routeTree.gen.ts")).toEqual({ kind: "named" });
  expect(generatedByPath("e2e/home.spec.ts-snapshots/home-1.png")).toEqual({ kind: "snapshot" });
  // Med's own editor themes.
  expect(
    generatedByHeader(["// Generated by scripts/generate-editor-themes.ts. Do not edit."]),
  ).toEqual({ kind: "header", source: "scripts/generate-editor-themes.ts" });
  // A note about editing far below the head is not a header.
  expect(generatedByHeader(["a", "b", "c", "d", "e", "// Do not edit"])).toBeNull();
  const paths = new Set([
    "package.json",
    "apps/med/package.json",
    "src/__snapshots__/app.test.ts.snap",
    "src/app.test.ts",
    "public/app.min.js",
    "public/app.js",
  ]);
  expect(generatedSource("bun.lock", { kind: "lockfile" }, paths)).toBe("package.json");
  expect(generatedSource("apps/med/bun.lock", { kind: "lockfile" }, paths)).toBe(
    "apps/med/package.json",
  );
  expect(generatedSource("Cargo.lock", { kind: "lockfile" }, paths)).toBeNull();
  expect(generatedSource("src/__snapshots__/app.test.ts.snap", { kind: "snapshot" }, paths)).toBe(
    "src/app.test.ts",
  );
  expect(generatedSource("public/app.min.js", { kind: "minified" }, paths)).toBe("public/app.js");
});

test("the part of a command that writes a generated file", () => {
  const lockfile = { path: "bun.lock", kind: "lockfile" } as const;
  expect(commandWrites(lockfile, "cd apps/med && bun add zod@4 2>&1 | tail -3")).toBe(
    "bun add zod@4",
  );
  expect(commandWrites(lockfile, "bun run test")).toBeNull();
  expect(commandWrites({ path: "Cargo.lock", kind: "lockfile" }, "cargo update -p serde")).toBe(
    "cargo update -p serde",
  );
  const snapshot = { path: "src/__snapshots__/a.test.ts.snap", kind: "snapshot" } as const;
  expect(commandWrites(snapshot, "bunx vitest run -u src/a.test.ts")).toBe(
    "bunx vitest run -u src/a.test.ts",
  );
  expect(commandWrites(snapshot, "bunx vitest run src/a.test.ts")).toBeNull();
  expect(
    commandWrites(
      {
        path: "src/web/editor-themes.ts",
        kind: "header",
        source: "scripts/generate-editor-themes.ts",
      },
      "bun scripts/generate-editor-themes.ts && bun run lint",
    ),
  ).toBe("bun scripts/generate-editor-themes.ts");
});
