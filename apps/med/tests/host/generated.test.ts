// Generated files through the production host (docs/GENERATED.md): each file
// of a review carries the mark that its path, its header, or Git attributes
// give, and a saved capture keeps it.

const directories: string[] = [];
const hosts: RunningHost[] = [];
const servers: Server[] = [];
afterEach(async () => {
  await Promise.all(hosts.splice(0).map((host) => host.close()));
  await Promise.all(servers.splice(0).map((server) => new Promise((done) => server.close(done))));
  vi.unstubAllEnvs();
  await Promise.all(
    directories.splice(0).map((path) => rm(path, { recursive: true, force: true })),
  );
});

const git = (cwd: string, args: string[]) =>
  execFileSync("git", args, {
    cwd,
    encoding: "utf8",
    env: {
      ...process.env,
      GIT_CONFIG_GLOBAL: "/dev/null",
      GIT_AUTHOR_NAME: "Med",
      GIT_AUTHOR_EMAIL: "med@example.invalid",
      GIT_COMMITTER_NAME: "Med",
      GIT_COMMITTER_EMAIL: "med@example.invalid",
    },
  }).trim();

const lines = (count: number, prefix: string) =>
  Array.from({ length: count }, (_, index) => `${prefix} ${index + 1}`).join("\n") + "\n";
/** A file whose header says a script writes it, with its change far below line 1. */
const schema = (value: string) =>
  `// Code generated by scripts/gen.ts. DO NOT EDIT.\n${lines(20, "export const field =")}export const version = "${value}";\n`;

async function fixture(options: { dependencyApi?: string } = {}) {
  const directory = await realpath(await mkdtemp(join(tmpdir(), "med generated ")));
  directories.push(directory);
  const repo = join(directory, "tide");
  const write = async (path: string, text: string) => {
    await mkdir(dirname(join(repo, path)), { recursive: true });
    await writeFile(join(repo, path), text);
  };
  await mkdir(repo);
  git(repo, ["init", "-q", "-b", "main"]);
  const start: Record<string, string> = {
    "package.json": '{ "dependencies": { "pg": "^8.13.0" } }\n',
    "bun.lock": lines(4, '"pg": ["pg@8.13.0"]'),
    "yarn.lock": lines(4, "pg@^8.13.0"),
    "src/app.ts": lines(4, "export const app ="),
    "src/schema.ts": schema("1"),
    "src/marked.ts": lines(4, "export const marked ="),
    "tests/__snapshots__/app.test.ts.snap": lines(4, "exports[`app`] ="),
    "dist/app.js": lines(4, "var app ="),
    "src/tables.ts": lines(4, "export const table ="),
    "src/handmade.ts": lines(4, "export const handmade ="),
    "logo.png": "\x89PNG\r\n\x1a\n\0\0one",
    // Attributes mark one hand-named file and one without diffs, and unmark
    // a lockfile and a file. The binary macro (-diff) does not mark images.
    ".gitattributes": [
      "src/marked.ts linguist-generated",
      "src/tables.ts -diff",
      "yarn.lock -linguist-generated",
      "src/handmade.ts -linguist-generated",
      "*.png binary",
      "",
    ].join("\n"),
  };
  for (const [path, text] of Object.entries(start)) await write(path, text);
  git(repo, ["add", "-f", "."]);
  git(repo, ["commit", "-q", "-m", "Start"]);
  // The working changes: one of each kind, and one ordinary file.
  await write("package.json", '{ "dependencies": { "pg": "^8.16.3" } }\n');
  await write("bun.lock", lines(4, '"pg": ["pg@8.16.3"]'));
  await write("yarn.lock", lines(4, "pg@^8.16.3"));
  await write("src/app.ts", lines(4, "export const app = 2 +"));
  await write("src/schema.ts", schema("2"));
  await write("src/marked.ts", lines(4, "export const marked = 2 +"));
  await write("tests/__snapshots__/app.test.ts.snap", lines(4, "exports[`app 2`] ="));
  await write("dist/app.js", lines(4, "var app = 2 +"));
  await write("src/tables.ts", lines(4, "export const table = 2 +"));
  await write("src/handmade.ts", lines(4, "export const handmade = 2 +"));
  await write("logo.png", "\x89PNG\r\n\x1a\n\0\0two");
  await write("src/routes.gen.ts", "export const routes = [];\n");
  await write(
    "src/client.ts",
    "/* @generated by the API client tool */\nexport const client = 1;\n",
  );
  const home = join(directory, "home");
  vi.stubEnv("MED_HOME_DIR", home);
  const stateDir = join(directory, "state");
  const boot = async () => {
    const started = await startHost({ repo, repos: [repo], stateDir, port: 0, ...options });
    hosts.push(started);
    return started;
  };
  let host = await boot();
  const api = async <T>(path: string, body?: unknown) => {
    const response = await fetch(`http://127.0.0.1:${host.port}${path}`, {
      method: body === undefined ? "GET" : "POST",
      headers: { authorization: `Bearer ${host.token}`, "content-type": "application/json" },
      ...(body === undefined ? {} : { body: JSON.stringify(body) }),
    });
    expect(response.status).toBe(200);
    return (await response.json()) as T;
  };
  /** The host again, on the same state directory. */
  const restart = async () => {
    await hosts.splice(hosts.indexOf(host), 1)[0]!.close();
    host = await boot();
  };
  /** `med review` or `med thread` against this host, as an agent runs it. */
  const med = (...args: string[]) => {
    const connection = ["--state-dir", stateDir, "--port", String(host.port)];
    return args[0] === "thread"
      ? runThreadSessionsCommand([...args.slice(1), ...connection], {
          print: () => {},
          environment: {},
          cwd: repo,
        })
      : runReviewCommand([...args, ...connection], { print: () => {}, environment: {} });
  };
  return { repo, api, home, restart, med };
}

const marks = (review: Pick<ReviewResponse, "files">) =>
  Object.fromEntries(review.files.map((file) => [file.path, file.generated ?? null]));

test("a review marks lockfiles, output, snapshots, headers, and attributes, and a capture keeps them", async () => {
  const { repo, api } = await fixture();
  const working = await api<ReviewResponse>("/api/review", {
    repo,
    comparison: { kind: "working" } satisfies Comparison,
  });
  expect(marks(working)).toEqual({
    "package.json": null,
    "bun.lock": { kind: "lockfile" },
    // An attribute unmarks a file that its name would mark.
    "yarn.lock": false,
    "src/app.ts": null,
    // The change is far from line 1: the working file's head names its generator.
    "src/schema.ts": { kind: "header", source: "scripts/gen.ts" },
    "src/marked.ts": { kind: "attributes" },
    "src/tables.ts": { kind: "attributes" },
    "src/handmade.ts": false,
    "logo.png": null,
    "tests/__snapshots__/app.test.ts.snap": { kind: "snapshot" },
    "dist/app.js": { kind: "output" },
    "src/routes.gen.ts": { kind: "named" },
    "src/client.ts": { kind: "header" },
  });

  // A saved capture keeps the marks that only the host could read.
  const saved = await api<{ id: string; targets: { id: string }[] }>("/api/reviews", {
    title: "Upgrade pg",
    targets: [{ repo, comparison: { kind: "working" } }],
  });
  const captured = await api<ReviewResponse>(
    `/api/reviews/${saved.id}/targets/${saved.targets[0]!.id}/review`,
  );
  expect(marks(captured)).toEqual(marks(working));

  // A commit reads attributes from its own tree. The patch of a change far
  // from line 1 does not show a header, so that file stays unmarked there.
  git(repo, ["add", "-A"]);
  git(repo, ["commit", "-q", "-m", "Upgrade"]);
  await writeFile(join(repo, ".gitattributes"), "");
  const commit = await api<ReviewResponse>("/api/review", {
    repo,
    comparison: { kind: "commit", commit: git(repo, ["rev-parse", "HEAD"]) },
  });
  expect(marks(commit)).toMatchObject({
    "yarn.lock": false,
    "src/handmade.ts": false,
    "logo.png": null,
    "src/marked.ts": { kind: "attributes" },
    "src/schema.ts": null,
    "src/client.ts": { kind: "header" },
  });
});

test("a linked worktree reads the repository's info/attributes", async () => {
  const directory = await realpath(await mkdtemp(join(tmpdir(), "med generated ")));
  directories.push(directory);
  const repo = join(directory, "tide");
  const linked = join(directory, "tide-linked");
  await mkdir(join(repo, "src"), { recursive: true });
  git(repo, ["init", "-q", "-b", "main"]);
  await writeFile(join(repo, "src/app.ts"), lines(4, "export const app ="));
  git(repo, ["add", "."]);
  git(repo, ["commit", "-q", "-m", "Start"]);
  git(repo, ["worktree", "add", "-q", "-b", "linked", linked]);
  // This clone's own override, with no .gitattributes in the checkout.
  await mkdir(join(repo, ".git", "info"), { recursive: true });
  await writeFile(join(repo, ".git", "info", "attributes"), "src/app.ts linguist-generated\n");
  await writeFile(join(linked, "src/app.ts"), lines(4, "export const app = 2 +"));
  vi.stubEnv("MED_HOME_DIR", join(directory, "home"));
  const host = await startHost({
    repo,
    repos: [repo],
    stateDir: join(directory, "state"),
    port: 0,
  });
  hosts.push(host);
  const response = await fetch(`http://127.0.0.1:${host.port}/api/review`, {
    method: "POST",
    headers: { authorization: `Bearer ${host.token}`, "content-type": "application/json" },
    body: JSON.stringify({ repo: linked, comparison: { kind: "working" } }),
  });
  expect(response.status).toBe(200);
  expect(marks((await response.json()) as ReviewResponse)).toEqual({
    "src/app.ts": { kind: "attributes" },
  });
});

test("provenance names a session's hand edits and the commands that wrote generated files", async () => {
  const { repo, api, home } = await fixture();
  const id = "55555555-5555-4555-8555-555555555555";
  const folder = join(home, ".claude", "projects", claudeProjectFolder(repo));
  await mkdir(folder, { recursive: true });
  const call = (index: number, name: string, input: object) =>
    JSON.stringify({
      type: "assistant",
      cwd: repo,
      sessionId: id,
      uuid: `u${index}`,
      timestamp: new Date().toISOString(),
      message: {
        role: "assistant",
        content: [{ type: "tool_use", id: `t${index}`, name, input }],
      },
    });
  await writeFile(
    join(folder, `${id}.jsonl`),
    [
      call(1, "Bash", { command: "bun install" }),
      call(2, "Edit", { file_path: join(repo, "dist/app.js") }),
      call(3, "Bash", { command: "cd tests && bunx vitest run -u 2>&1 | tail -5" }),
      // The last command that writes a lockfile names it.
      call(4, "Bash", { command: "bun add pg@8.16.3" }),
      call(5, "Bash", { command: "bun run lint" }),
    ].join("\n") + "\n",
  );
  const answer = await api<{ files: Record<string, Provenance> }>("/api/review/provenance", {
    repo,
    sessions: [{ agent: "claude", id }],
    files: [
      { path: "bun.lock", kind: "lockfile" },
      { path: "dist/app.js", kind: "output" },
      { path: "tests/__snapshots__/app.test.ts.snap", kind: "snapshot" },
      { path: "src/schema.ts", kind: "header", source: "scripts/gen.ts" },
    ],
  });
  expect(answer.files).toEqual({
    "bun.lock": { command: "bun add pg@8.16.3" },
    "dist/app.js": { edited: true },
    "tests/__snapshots__/app.test.ts.snap": { command: "bunx vitest run -u" },
  });
});

test("dependency lookups ask deps.dev once for each version and keep the answers", async () => {
  const asked: string[] = [];
  const server = createServer((request, response) => {
    asked.push(decodeURIComponent(request.url ?? ""));
    response.setHeader("content-type", "application/json");
    if (request.url?.includes("private-thing")) {
      response.statusCode = 404;
      response.end("{}");
      return;
    }
    response.end(
      JSON.stringify({
        publishedAt: "2025-06-27T14:52:44Z",
        licenses: ["MIT"],
        advisoryKeys: [{ id: "GHSA-1" }],
        isDeprecated: false,
      }),
    );
  });
  servers.push(server);
  await new Promise<void>((done) => server.listen(0, "127.0.0.1", done));
  const port = (server.address() as { port: number }).port;
  const { api, restart } = await fixture({ dependencyApi: `http://127.0.0.1:${port}` });
  const lookup = () =>
    api<{ packages: DependencyInfo[] }>("/api/dependencies", {
      packages: [
        { name: "@types/pg", version: "8.16.3" },
        { name: "private-thing", version: "1.0.0" },
      ],
    });
  const expected = [
    {
      name: "@types/pg",
      version: "8.16.3",
      licence: "MIT",
      publishedAt: Date.parse("2025-06-27T14:52:44Z"),
      advisories: 1,
    },
    { name: "private-thing", version: "1.0.0", unknown: true },
  ];
  expect((await lookup()).packages).toEqual(expected);
  expect(asked.sort()).toEqual([
    "/v3/systems/npm/packages/@types/pg/versions/8.16.3",
    "/v3/systems/npm/packages/private-thing/versions/1.0.0",
  ]);
  // Kept in memory, and on disk for the next host.
  expect((await lookup()).packages).toEqual(expected);
  await restart();
  expect((await lookup()).packages).toEqual(expected);
  expect(asked).toHaveLength(2);
});

test("med review --generated marks the files that a hand-off names, in each version", async () => {
  const { repo, api, med } = await fixture();
  type Saved = { id: string; targets: { id: string }[]; iterations?: { targetIds: string[] }[] };
  const current = async (id: string) => {
    const saved = await api<Saved>(`/api/reviews/${id}`);
    const target = saved.iterations!.at(-1)!.targetIds[0]!;
    return marks(await api<ReviewResponse>(`/api/reviews/${id}/targets/${target}/review`));
  };
  // Files and a glob. Files that Git attributes unmark stay unmarked, and a
  // lockfile that its path marks keeps its kind.
  await med(
    "create",
    "--title",
    "Regenerate client",
    "--key",
    "client",
    "--repo",
    repo,
    "--working",
    "--generated",
    "src/app.ts",
    "src/handmade.ts",
    "*.lock",
    "--no-pr",
    "--no-session",
  );
  const { id } = await api<{ id: string }>("/api/reviews/by-key", { key: "client" });
  expect(await current(id)).toMatchObject({
    "src/app.ts": { kind: "declared" },
    "src/handmade.ts": false,
    "package.json": null,
    "yarn.lock": false,
    "bun.lock": { kind: "lockfile" },
  });

  // A version from update --paths marks its own files.
  await med(
    "update",
    "--key",
    "client",
    "--paths",
    join(repo, "src"),
    "--generated",
    "src/*.ts",
    "--no-session",
  );
  expect(await current(id)).toMatchObject({
    "src/app.ts": { kind: "declared" },
    "src/marked.ts": { kind: "attributes" },
    "src/schema.ts": { kind: "header", source: "scripts/gen.ts" },
  });

  // So does med thread show; a version marks only the files that it names.
  await med("thread", "show", "--key", "client", "--working", "--generated", "package.json");
  expect(await current(id)).toMatchObject({
    "package.json": { kind: "declared" },
    "src/app.ts": null,
  });

  // New notes capture the version again; the marks stay.
  await api(`/api/reviews/${id}/iterations`, {});
  expect((await current(id))["package.json"]).toEqual({ kind: "declared" });
});
