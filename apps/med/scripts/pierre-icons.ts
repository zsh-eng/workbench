const repo = process.argv[2];
if (!repo) throw new Error("Usage: bun scripts/pierre-icons.ts <pierrecomputer/icons checkout>");
const commit = execFileSync("git", ["-C", repo, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();

/** One SVG element as [tag, attributes]: only what draws, in currentColor. */
type Shape = [string, Record<string, string | number>];
const KEEP = new Set([
  "d",
  "opacity",
  "fill-rule",
  "clip-rule",
  "cx",
  "cy",
  "r",
  "x",
  "y",
  "width",
  "height",
  "rx",
]);
const camel = (name: string) => name.replace(/-(\w)/g, (_, c: string) => c.toUpperCase());

function read(name: string) {
  const svg = readFileSync(join(repo, "svg", `Icon${name}.svg`), "utf8");
  const box = svg.match(/viewBox="([^"]+)"/)![1]!;
  const shapes: Shape[] = [];
  for (const [, tag, body] of svg.matchAll(/<(path|circle|rect)\b([^>]*)\/?>/g)) {
    const attributes: Record<string, string | number> = {};
    for (const [, key, value] of body!.matchAll(/([\w-]+)="([^"]*)"/g)) {
      if (key === "fill" && value !== "black" && value !== "none")
        throw new Error(`Icon${name}: a colour other than black (${value}).`);
      if (key === "fill" && value === "none") attributes.fill = "none";
      if (KEEP.has(key!))
        attributes[camel(key!)] = /^-?[\d.]+$/.test(value!) ? Number(value) : value!;
    }
    shapes.push([tag!, attributes]);
  }
  if (svg.includes("<g") || svg.includes("<mask") || svg.includes("<defs"))
    throw new Error(`Icon${name}: groups, masks, and definitions are not copied.`);
  return { box, shapes };
}

const entries = Object.entries(ICONS).map(([med, source]) => {
  const [name, turn] = typeof source === "string" ? [source, 0] : source;
  return `  ${med}: ${JSON.stringify({ source: name, ...read(name), ...(turn && { turn }) })},`;
});

